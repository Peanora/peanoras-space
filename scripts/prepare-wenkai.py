"""Create a home/shell WOFF2 face and disjoint Unicode fallback shards.

Usage: python scripts/prepare-wenkai.py path/to/LXGWWenKaiLite-Regular.ttf
Requires fonttools[woff]. Font source: https://github.com/lxgw/LxgwWenKai-Lite
The OFL and additional web conversion permission are shipped with the font.
"""
import argparse
import json
from pathlib import Path
import site
from collections import defaultdict
from copy import deepcopy

parser = argparse.ArgumentParser()
parser.add_argument("source", type=Path, nargs="?", help="Original TTF or preserved full WOFF2")
parser.add_argument("--tools", type=Path, help="Optional folder containing fonttools and brotli")
args = parser.parse_args()
if args.tools:
    site.addsitedir(str(args.tools))
from fontTools.ttLib import TTFont
from fontTools import subset

root = Path(__file__).resolve().parents[1]
font_dir = root / "src/assets/fonts"
font = TTFont(args.source or font_dir / "LXGWWenKaiLite-Regular.woff2", recalcTimestamp=False)
supported = set(font.getBestCmap())
characters = set(range(32, 127))
# Keep the first-visit face focused on the shell and home. Including all note
# bodies here would make every visitor download the entire reading vocabulary.
sources = [root / "src/App.vue"]
for folder in ("layout", "home", "ui"):
    sources.extend((root / f"src/components/{folder}").glob("*.vue"))
sources.extend(root / f"src/components/content/{name}.vue" for name in ("HomeScene", "ChapterTicket"))
sources.extend((root / "src/data").glob("*.js"))
for source in sources:
    characters.update(map(ord, source.read_text(encoding="utf-8")))

content = json.loads((root / "src/data/content.json").read_text(encoding="utf-8"))
shell_content = [content["pages"]["home"]]
for block in content["pages"]["world"]["blocks"]:
    if block["type"] == "profile":
        shell_content.append(block["data"])
    elif block["type"] == "unityNotes":
        shell_content.extend({key: note.get(key, "") for key in ("title", "category")}
                             for note in block["data"]["items"] if not note.get("draft"))
for block in content["pages"]["music"]["blocks"]:
    if block["type"] == "songs" and not block.get("hidden"):
        shell_content.extend({key: song.get(key, "") for key in ("title", "artist")}
                             for song in block["data"]["items"])
for block in content["pages"]["little"]["blocks"]:
    if block["type"] == "notes" and not block.get("hidden"):
        shell_content.append(block["data"])
characters.update(map(ord, json.dumps(shell_content, ensure_ascii=False)))
characters &= supported
blocks = defaultdict(set)
for codepoint in supported - characters:
    blocks[codepoint // 256].add(codepoint)
# Dense ranges stay local to a Unicode page. Pool sparse ranges so a rare
# character does not create a separate font/request for only one or two glyphs.
shards = {f"{block:04x}": values for block, values in blocks.items() if len(values) >= 32}
sparse = sorted(set().union(*(values for values in blocks.values() if len(values) < 32)))
for offset in range(0, len(sparse), 256):
    shards[f"extra-{offset // 256:02x}"] = set(sparse[offset:offset + 256])

def ranges_for(values):
    """Compact adjacent codepoints without declaring glyphs in another face."""
    runs = []
    start = previous = None
    for value in sorted(values):
        if previous is not None and value != previous + 1:
            runs.append((start, previous))
            start = None
        if start is None:
            start = value
        previous = value
    if start is not None:
        runs.append((start, previous))
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in runs)

def save_face(values, output):
    # Reuse a generated face only when its actual glyph coverage matches.
    if not output.exists() or set(TTFont(output).getBestCmap()) != values:
        if not getattr(font, "_shard_source_decoded", False):
            # Decode once; copying a lazy WOFF2 reader repeats reconstruction.
            font.ensureDecompiled()
            font._shard_source_decoded = True
            print("Source font decoded.", flush=True)
        face = deepcopy(font)
        options = subset.Options()
        options.flavor = "woff2"
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=values)
        subsetter.subset(face)
        face.flavor = "woff2"
        face.save(output)
    relative = output.relative_to(font_dir).as_posix()
    return ('@font-face { font-family: "Peanora WenKai"; '
            f'src: url("../assets/fonts/{relative}") format("woff2"); '
            'font-style: normal; font-weight: 400; font-display: swap; '
            f'unicode-range: {ranges_for(values)}; }}\n')

shard_dir = font_dir / "wenkai"
shard_dir.mkdir(exist_ok=True)
css = ['/* Generated by scripts/prepare-wenkai.py; disjoint web-only OFL subsets. */\n']
css.append(save_face(characters, font_dir / "LXGWWenKaiLite-Core.woff2"))
for index, (name, values) in enumerate(sorted(shards.items())):
    css.append(save_face(values, shard_dir / f"{name}.woff2"))
    if index % 20 == 0:
        print(f"Prepared {index + 1}/{len(shards)} shards.", flush=True)
# This folder contains only generated shards; remove obsolete generated files.
for obsolete in shard_dir.glob("*.woff2"):
    if obsolete.stem not in shards:
        obsolete.unlink()
(root / "src/styles/wenkai.css").write_text("".join(css), encoding="utf-8")
print(f"Core: {len(characters)} characters; fallback: {len(shards)} on-demand shards.")
print(f"Core size: {(font_dir / 'LXGWWenKaiLite-Core.woff2').stat().st_size:,} bytes")
print(f"Largest shard: {max(p.stat().st_size for p in shard_dir.glob('*.woff2')):,} bytes")
