"""Create web-only WOFF2 faces: a small current-content face + full future-text fallback.

Usage: python scripts/prepare-wenkai.py path/to/LXGWWenKaiLite-Regular.ttf
Requires fonttools[woff]. Font source: https://github.com/lxgw/LxgwWenKai-Lite
The OFL and additional web conversion permission are shipped with the font.
"""
import argparse
from pathlib import Path
import site

parser = argparse.ArgumentParser()
parser.add_argument("source", type=Path)
parser.add_argument("--tools", type=Path, help="Optional folder containing fonttools and brotli")
args = parser.parse_args()
if args.tools:
    site.addsitedir(str(args.tools))
from fontTools.ttLib import TTFont
from fontTools import subset

root = Path(__file__).resolve().parents[1]
font_dir = root / "src/assets/fonts"
font = TTFont(args.source)
supported = set(font.getBestCmap())
characters = set(range(32, 127))
for source in (root / "src").rglob("*"):
    if source.suffix in (".vue", ".js", ".json"):
        characters.update(map(ord, source.read_text(encoding="utf-8")))
characters &= supported
font.flavor = "woff2"
font.save(font_dir / "LXGWWenKaiLite-Regular.woff2")
options = subset.Options()
options.flavor = "woff2"
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=characters)
subsetter.subset(font)
font.save(font_dir / "LXGWWenKaiLite-Core.woff2")

# The later, restricted face wins for existing text. New text automatically uses
# the complete earlier face; adding a signature never requires regenerating fonts.
ranges = ",".join(f"U+{value:X}" for value in sorted(characters))
(root / "src/styles/wenkai.css").write_text(
    '/* Generated by scripts/prepare-wenkai.py; web-only OFL font conversion. */\n'
    '@font-face { font-family: "Peanora WenKai"; src: url("../assets/fonts/LXGWWenKaiLite-Regular.woff2") format("woff2"); font-style: normal; font-weight: 400; font-display: swap; }\n'
    '@font-face { font-family: "Peanora WenKai"; src: url("../assets/fonts/LXGWWenKaiLite-Core.woff2") format("woff2"); font-style: normal; font-weight: 400; font-display: swap; unicode-range: '
    + ranges + '; }\n', encoding="utf-8",
)
print(f"Core face: {len(characters)} characters. Complete face: {len(supported)} characters.")
for output in font_dir.glob("LXGWWenKaiLite-*.woff2"):
    print(f"{output.name}: {output.stat().st_size:,} bytes")
